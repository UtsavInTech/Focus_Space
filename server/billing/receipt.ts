import { PLANS, currentPlanId } from '@/billing/plans';
import { ApiError } from '../http';
import type { UsageDb } from '../usage/db';

/**
 * A self-hosted receipt for a completed payment (Layer 2C follow-up).
 *
 * Razorpay only auto-generates a hosted invoice for *subscription* charges, never for a one-off order —
 * and even that hosted invoice was never fetched or surfaced anywhere in this codebase. Rather than add a
 * second, Razorpay-dependent code path that this environment has no live credentials to verify end to end,
 * this builds one small, consistent receipt from data FocusSpace already owns and already records for
 * every payment (`payments` table: plan, period, currency, amount, status, date, Razorpay payment id) —
 * it works identically for a subscription charge and a one-off order, and needs no additional call to
 * Razorpay or any new stored field.
 *
 * Ownership is enforced here, not just by routing: a payment id belongs to exactly one user, and this
 * throws the same "not found" (never a distinguishing "forbidden") for a payment that doesn't exist and
 * one that exists but belongs to someone else — so probing payment ids never confirms which is which.
 */

export interface Receipt {
  paymentId: string;
  html: string;
}

const escapeHtml = (value: string): string =>
  value.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c] ?? c);

const money = (amountMinor: number, currency: string): string => {
  const value = amountMinor / 100;
  return currency === 'INR' ? `₹${value.toLocaleString('en-IN')}` : `$${value.toFixed(2)}`;
};

export function buildReceipt(db: UsageDb, user: { id: string; email: string | null }, paymentId: string): Receipt {
  const row = db.getPayment(paymentId);
  // Same message either way — a payment that doesn't exist and one that exists but isn't yours must be
  // indistinguishable to the caller, or the endpoint becomes a way to probe which payment ids are real.
  if (!row || row.user_id !== user.id) throw new ApiError(404, 'invalid_request', 'No receipt found for that payment.');

  const planName = PLANS.find((p) => p.id === currentPlanId(row.plan))?.name ?? row.plan;
  const credit = row.credit_minor ?? 0;
  const term = row.period === 'lifetime' ? 'for life' : row.period === 'annual' ? '12 months' : '1 month';
  const date = new Date(row.created_at).toLocaleDateString('en-US', { day: 'numeric', month: 'long', year: 'numeric' });
  const amount = money(row.amount_minor, row.currency);
  const buyer = escapeHtml(user.email ?? 'your FocusSpace account');
  const paidStatus = row.status === 'captured' ? 'Paid' : escapeHtml(row.status);

  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<title>FocusSpace receipt · ${escapeHtml(row.id)}</title>
<meta name="viewport" content="width=device-width, initial-scale=1" />
<style>
  :root { color-scheme: light; }
  body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; max-width: 560px; margin: 48px auto; padding: 0 24px; color: #1a1a1a; background: #fff; }
  .brand { font-size: 15px; font-weight: 700; letter-spacing: -0.01em; }
  h1 { font-size: 20px; margin: 24px 0 4px; }
  .muted { color: #666; font-size: 13px; margin: 0; }
  table { width: 100%; border-collapse: collapse; margin-top: 28px; }
  td { padding: 10px 0; border-bottom: 1px solid #e5e5e5; font-size: 14px; vertical-align: top; }
  td:first-child { color: #666; }
  td:last-child { text-align: right; font-weight: 600; }
  tr.total td { font-size: 17px; border-bottom: none; padding-top: 18px; }
  .foot { margin-top: 32px; font-size: 12px; color: #999; line-height: 1.5; }
  .print { margin-top: 28px; }
  button { font: inherit; padding: 8px 16px; border-radius: 8px; border: 1px solid #d8d8d8; background: #fff; cursor: pointer; }
  @media print { .print { display: none; } body { margin: 0; } }
</style>
</head>
<body>
  <div class="brand">FocusSpace</div>
  <h1>Receipt</h1>
  <p class="muted">Billed to ${buyer}</p>
  <table>
    <tr><td>Date</td><td>${date}</td></tr>
    <tr><td>Plan</td><td>${escapeHtml(planName)} · ${term}</td></tr>
    ${credit ? `<tr><td>Price</td><td>${money(row.amount_minor + credit, row.currency)}</td></tr>\n    <tr><td>${escapeHtml(row.credit_note ?? 'Credit')}</td><td>−${money(credit, row.currency)}</td></tr>` : ''}
    <tr><td>Payment ID</td><td>${escapeHtml(row.id)}</td></tr>
    <tr><td>Status</td><td>${paidStatus}</td></tr>
    <tr class="total"><td>Total</td><td>${amount}</td></tr>
  </table>
  <p class="foot">This receipt was generated by FocusSpace for your records. Questions about a charge? Contact support with the payment ID above.</p>
  <div class="print"><button onclick="window.print()" type="button">Print / save as PDF</button></div>
</body>
</html>`;

  return { paymentId: row.id, html };
}
